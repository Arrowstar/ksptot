        function startupFcn(app, optimizer, output)
            app.Optimizer = optimizer;
            app.Output = output;
            app.Options = optimizer.getOptions();

            centerUIFigure(app.UIFigure);
            applySelectedThemeToApp(app);

            populateGUI(app);
            applyTooltips(app);

            app.UIFigure.Visible = 'on';
            uiwait(app.UIFigure);
        end

