        function buildGuidanceTab(app)
            %buildGuidanceTab A read-only tab with an ordered "if the solve
            %   misbehaves, try this" playbook.  Rendered as a single HTML
            %   uilabel so it themes with the rest of the app (the AppThemer
            %   sets the label FontColor, which HTML text without its own color
            %   tags inherits) and scrolls inside a fit-height grid.
            app.GuidanceTab = uitab(app.TabGroup, 'Title', 'Guidance');

            g = uigridlayout(app.GuidanceTab, [1 1]);
            g.ColumnWidth = {'1x'};
            g.RowHeight = {'fit'};
            g.Padding = [10 10 10 10];
            g.Scrollable = 'on';
            app.GuidanceTabGrid = g;

            lbl = uilabel(g);
            lbl.Interpreter = 'html';
            lbl.WordWrap = 'on';
            lbl.VerticalAlignment = 'top';
            lbl.Text = getGuidanceText(app);
            lbl.Layout.Row = 1;
            lbl.Layout.Column = 1;
            app.GuidanceText = lbl;
        end

        function g = makeTabGrid(~, parentTab, nRows)
            g = uigridlayout(parentTab, [nRows 2]);
            g.ColumnWidth = {'1x', '1x'};
            g.RowHeight = repmat({'fit'}, 1, nRows);
            g.Padding = [8 8 8 8];
            g.RowSpacing = 6;
            g.ColumnSpacing = 8;
            g.Scrollable = 'on';
        end

        function createPanel(app, tabGrid, rowInCol, colIdx, panelKey, titleText, rows)
            p = uipanel(tabGrid, 'Title', titleText);
            p.FontWeight = 'bold';
            p.Layout.Row = rowInCol;
            p.Layout.Column = colIdx;
            app.([panelKey 'Panel']) = p;

            nRows = numel(rows);
            g = uigridlayout(p, [nRows 2]);
            g.ColumnWidth = {'fit', '1x'};
            g.RowHeight = repmat({'fit'}, 1, nRows);
            g.Padding = [8 8 8 8];
            g.RowSpacing = 4;
            g.ColumnSpacing = 6;
            app.([panelKey 'Grid']) = g;

            for i = 1:nRows
                createRow(app, g, i, rows{i});
            end
        end

        function createRow(app, panelGrid, rowIdx, rowSpec)
            name = rowSpec{1};
            labelText = rowSpec{2};
            kind = rowSpec{3};
            aux = rowSpec{4};

            switch kind
                case 'check'
                    cb = uicheckbox(panelGrid);
                    cb.Text = labelText;
                    cb.Layout.Row = rowIdx;
                    cb.Layout.Column = [1 2];
                    app.(name) = cb;

                otherwise
                    lbl = uilabel(panelGrid);
                    lbl.Text = [labelText '  '];
                    lbl.HorizontalAlignment = 'right';
                    lbl.Layout.Row = rowIdx;
                    lbl.Layout.Column = 1;
                    app.([name 'Lbl']) = lbl;

                    switch kind
                        case {'num', 'char'}
                            ctrl = uieditfield(panelGrid, 'text');
                        case 'enum'
                            ctrl = uidropdown(panelGrid);
                            m = enumeration(aux);
                            [~, I] = sort({m.name});
                            m = m(I);
                            ctrl.Items = {m.name};
                            ctrl.ItemsData = m;
                    end
                    ctrl.Layout.Row = rowIdx;
                    ctrl.Layout.Column = 2;
                    app.(name) = ctrl;
            end

            rec = struct('name', name, 'label', labelText, 'kind', kind, ...
                         'enumClass', '', 'lb', -Inf, 'ub', Inf, 'isInt', false);
            if strcmp(kind, 'enum')
                rec.enumClass = aux;
            elseif strcmp(kind, 'num') && not(isempty(aux))
                rec.lb = aux(1);
                rec.ub = aux(2);
                rec.isInt = logical(aux(3));
            end
            app.Fields(end+1) = rec;
        end

        function populateGUI(app)
            for i = 1:numel(app.Fields)
                f = app.Fields(i);
                switch f.kind
                    case 'num'
                        app.(f.name).Value = numToStr(app, app.Options.(f.name));
                    case 'char'
                        app.(f.name).Value = app.Options.(f.name);
                    case 'check'
                        app.(f.name).Value = app.Options.(f.name);
                    case 'enum'
                        app.(f.name).Value = app.Options.(f.name);
                end
            end
        end

        function applyTooltips(app)
            % Build a mouse-over tooltip for every control: a detailed
            % description of what the option does, practical guidance on when
            % to change it / what to set it to, and its default value.  Each
            % entry in getOptionDescriptions is a struct with a 'desc' field
            % (what it does) and a 'use' field (when-to-use guidance; may be
            % empty for options that need no extra guidance).
            desc     = getOptionDescriptions(app);
            defaults = AdamNlOptOptions();   % a fresh object holds the defaults

            for i = 1:numel(app.Fields)
                f = app.Fields(i);
                if isfield(desc, f.name)
                    dtxt = desc.(f.name).desc;
                    utxt = desc.(f.name).use;
                else
                    dtxt = f.label;
                    utxt = '';
                end
                defStr = formatDefault(app, f, defaults.(f.name));

                if isempty(utxt)
                    tip = sprintf('%s\n\nDefault: %s', dtxt, defStr);
                else
                    tip = sprintf('%s\n\nWhen to use: %s\n\nDefault: %s', ...
                                  dtxt, utxt, defStr);
                end

                app.(f.name).Tooltip = tip;
                if isprop(app, [f.name 'Lbl']) && not(isempty(app.([f.name 'Lbl'])))
                    app.([f.name 'Lbl']).Tooltip = tip;
                end
            end
        end

        function s = formatDefault(app, f, v)
            switch f.kind
                case 'check'
                    if v, s = 'true'; else, s = 'false'; end
                case 'enum'
                    s = char(v.name);
                case 'char'
                    if isempty(v), s = '(none)'; else, s = char(v); end
                otherwise   % num
                    if isnan(v)
                        s = 'automatic (set by the solver)';
                    else
                        s = numToStr(app, v);
                        if isempty(s), s = 'automatic (set by the solver)'; end
                    end
            end
        end

        function [ok, errMsg] = validateGUI(app)
            errMsg = {};
            for i = 1:numel(app.Fields)
                f = app.Fields(i);
                if strcmp(f.kind, 'num')
                    enteredStr = strtrim(app.(f.name).Value);
                    if not(isempty(enteredStr))
                        value = str2double(enteredStr);
                        errMsg = validateNumber(value, f.label, f.lb, f.ub, ...
                                                f.isInt, errMsg, enteredStr);
                    end
                end
            end
            ok = isempty(errMsg);
        end

        function writeGUIToOptions(app)
            for i = 1:numel(app.Fields)
                f = app.Fields(i);
                switch f.kind
                    case 'num'
                        app.Options.(f.name) = strToNum(app, app.(f.name).Value);
                    case 'char'
                        app.Options.(f.name) = char(app.(f.name).Value);
                    case 'check'
                        app.Options.(f.name) = app.(f.name).Value;
                    case 'enum'
                        app.Options.(f.name) = app.(f.name).Value;
                end
            end
        end

        function onSaveClose(app)
            [ok, errMsg] = validateGUI(app);
            if not(ok)
                uialert(app.UIFigure, strjoin(errMsg, newline), 'Invalid Options');
                return;
            end

            writeGUIToOptions(app);
            app.Output.output = {true};
            delete(app.UIFigure);
        end

        function s = numToStr(~, v)
            if isnan(v)
                s = '';
            elseif isinf(v)
                s = num2str(v);
            else
                s = fullAccNum2Str(v);
            end
        end

        function v = strToNum(~, value)
            s = strtrim(value);
            if isempty(s)
                v = NaN;
            else
                v = str2double(s);
            end
        end

